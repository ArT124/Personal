// The learning roadmap (v2). Topics are grouped into phases and ordered so each
// one only needs what came before it. Problems inside a topic go from easy to hard.
// The "Mixed Review" topics are checkpoints with problems from earlier phases
// on purpose: deciding *which* pattern to use is a skill you only build by
// meeting unlabeled problems (interleaved practice).
// See docs/CURRICULUM.md for the research and reasoning behind this order.
//
// p(leetcodeNumber, title, slug, difficulty E/M/H, one-line hint)
// The slug builds the link: https://leetcode.com/problems/<slug>/
// Slugs are the progress keys, so never rename a slug that is already in use.

const p = (num, title, slug, d, hint) => ({
  num,
  title,
  slug,
  difficulty: { E: 'Easy', M: 'Medium', H: 'Hard' }[d],
  hint,
});

